/**
 * Step 24A production environment contract.
 *
 * Every entry here was derived by reading the code that reads the variable,
 * not by reading documentation. `environment.test.ts` re-derives the set of
 * variable names from the repository on every run and fails when this contract
 * and the code disagree in either direction, so a new `process.env` read
 * cannot reach production without being classified first.
 *
 * This file records the expected *presence* of a variable and never its value.
 * There is no field a value could be written into, and `secrets.test.ts`
 * additionally refuses any plausible credential in the release artifacts.
 */

export type EnvClassification =
  /** The Admin workspace cannot serve a signed-in operator without it. */
  | "REQUIRED_FOR_ADMIN_CORE"
  /** One optional capability needs it; Admin core runs without it. */
  | "REQUIRED_FOR_OPTIONAL_FEATURE"
  /** A switch that turns a capability on. Never a credential. */
  | "FEATURE_GATE"
  /** Credential material for an external provider. */
  | "PROVIDER_SECRET"
  /** Configuration that is safe to read aloud. */
  | "NON_SECRET_CONFIGURATION"
  /** Read only by test or test-only code. Must never be set in production. */
  | "TEST_ONLY"
  /** Still read somewhere but no longer serving a purpose. */
  | "DEPRECATED_UNUSED"

/** Which deployment the variable is meant to exist in. */
export type EnvScope =
  | "PRODUCTION_AND_PREVIEW"
  | "PRODUCTION_ONLY"
  | "PREVIEW_AND_DEVELOPMENT_ONLY"
  /** Supplied by the platform; an operator never sets it. */
  | "PLATFORM_PROVIDED"
  | "LOCAL_DEVELOPMENT_ONLY"

/**
 * What production is expected to look like at Admin cutover, before any
 * capability activation. `ABSENT` is a real requirement rather than an
 * absence of one: static AWS credentials present in production deliberately
 * disable evidence storage, so setting them would be a regression.
 */
export type EnvExpectation = "PRESENT" | "ABSENT" | "OPTIONAL"

export type EnvApp = "marketing" | "admin" | "customer"

export type EnvVariable = {
  name: string
  /** Workspaces whose runtime reads it. */
  apps: EnvApp[]
  classification: EnvClassification
  secret: boolean
  scope: EnvScope
  /** Expected presence at Admin production cutover. Never a value. */
  atAdminCutover: EnvExpectation
  /** The capability or behaviour the variable controls. */
  controls: string
  /** What the code does when the variable is absent or unparseable. */
  whenAbsent: string
  /** True when Admin production access itself cannot proceed without it. */
  blocksAdminLaunch: boolean
  /** True when absence costs only the optional capability named in `controls`. */
  blocksOptionalCapabilityOnly: boolean
  /** Repository-relative files that read it. Checked against disk. */
  readBy: string[]
}


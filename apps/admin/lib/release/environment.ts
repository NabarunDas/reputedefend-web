export function variable(name: string): EnvVariable | undefined {
  return environmentContract.find(entry => entry.name === name)
}

/** Variables without which a signed-in Admin cannot work at all. */
export function adminLaunchBlocking(): EnvVariable[] {
  return environmentContract.filter(entry => entry.blocksAdminLaunch)
}

/** Variables production is expected to be missing at Admin cutover. */
export function expectedAbsentAtCutover(): EnvVariable[] {
  return environmentContract.filter(entry => entry.atAdminCutover === "ABSENT")
}
